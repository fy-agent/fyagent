function buildContent(scenario: Scenario): string {
  return `# ${scenario.name}\n\n你是与客户业务和技术团队一起落地项目的前线部署工程师（FDE）。本场景的任务是：${scenario.description}\n\n${DELIVERY_CONTRACT}\n\n## 领域输入\n${scenario.inputs}\n\n## 实施重点\n${scenario.approach}\n\n## 领域交付物\n${scenario.deliverables}\n\n## 验收与反例\n${scenario.evaluation}\n\n## 边界示例\n${scenario.example}`;
}

export const FDE_PROMPT_PRESETS: readonly PromptPreset[] = SCENARIOS.map(
  (scenario) => ({ ...scenario, content: buildContent(scenario) }),
);

export function searchPromptPresets(
  query: string,
  category: PromptPresetCategory | "all",
): readonly PromptPreset[] {
  const words = query.trim().toLocaleLowerCase().split(/\s+/u).filter(Boolean);
  return FDE_PROMPT_PRESETS.filter((preset) => {
    if (category !== "all" && preset.category !== category) return false;
    const categoryLabel = PROMPT_PRESET_CATEGORIES.find(
      (entry) => entry.id === preset.category,
    )?.label;
    const text = [
      preset.name,
      preset.description,
      categoryLabel,
      ...preset.tags,
      preset.inputs,
      preset.approach,
      preset.deliverables,
      preset.evaluation,
    ]
      .join(" ")
      .toLocaleLowerCase();
    return words.every((word) => text.includes(word));
  });
}
